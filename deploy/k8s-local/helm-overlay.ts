/**
 * Builds the local overlay on the Helm chart instead of the plain manifests
 * (`up.sh --helm`). It writes a kustomize directory whose kustomization is
 * this directory's, except that the deploy/k8s-scale objects the chart owns
 * come from `helm template` (chart.yaml). Every generator, patch and local
 * resource is reused as it is, so the two overlays cannot drift:
 * tests/deploy/helm-parity.test.ts builds both and compares them.
 *
 *   bun deploy/k8s-local/helm-overlay.ts [--local DIR] [--chart DIR] [--values FILE] --out DIR
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { isAbsolute, join, relative, resolve } from "node:path";
import { parse, stringify } from "yaml";

const here = import.meta.dir;
const args = process.argv.slice(2);
const arg = (name: string, dflt?: string): string => {
  const i = args.indexOf(`--${name}`);
  const v = i >= 0 ? args[i + 1] : dflt;
  if (!v) throw new Error(`--${name} is required`);
  return resolve(v);
};
const local = arg("local", here);
const chart = arg("chart", join(here, "../helm/slaude"));
const values = arg("values", join(local, "helm-values.yaml"));
const out = arg("out");

/** deploy/k8s-scale files the overlay keeps: the chart renders neither. */
const KEEP = new Set(["00-namespace.yaml", "90-dev-datastores.yaml"]);
const SCALE = "../k8s-scale/";

const k = parse(readFileSync(join(local, "kustomization.yaml"), "utf8"));
/** A path relative to the local overlay, made relative to the output directory. */
const rebase = (p: string): string => (isAbsolute(p) ? p : relative(out, join(local, p)));

const resources: string[] = [];
let chartAdded = false;
for (const r of k.resources as string[]) {
  const owned = r.startsWith(SCALE) && !KEEP.has(r.slice(SCALE.length));
  if (!owned) resources.push(rebase(r));
  else if (!chartAdded) {
    resources.push("chart.yaml");
    chartAdded = true;
  }
}
k.resources = resources;
for (const gen of [...(k.secretGenerator ?? []), ...(k.configMapGenerator ?? [])]) {
  if (gen.envs) gen.envs = gen.envs.map(rebase);
  if (gen.files) gen.files = gen.files.map((f: string) => (f.includes("=") ? `${f.split("=")[0]}=${rebase(f.split("=")[1]!)}` : rebase(f)));
}

const r = Bun.spawnSync(["helm", "template", "slaude", chart, "-n", k.namespace ?? "slaude-scale", "-f", values]);
if (r.exitCode !== 0) {
  process.stderr.write(r.stderr);
  process.exit(1);
}
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "chart.yaml"), r.stdout);
writeFileSync(join(out, "kustomization.yaml"), `# Generated by deploy/k8s-local/helm-overlay.ts from ${relative(out, join(local, "kustomization.yaml"))}. Do not edit.\n${stringify(k)}`);
console.log(out);
